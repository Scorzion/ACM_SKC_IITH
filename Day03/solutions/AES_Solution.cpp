static const uint8_t RC[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

std::vector<uint8_t> h2b(const std::string& h) {
    std::vector<uint8_t> b;
    for (size_t i = 0; i + 1 < h.size(); i += 2) {
        uint8_t hi = 0, lo = 0;
        char ch = h[i], cl = h[i + 1];
        if (ch >= '0' && ch <= '9') hi = ch - '0';
        else if (ch >= 'A' && ch <= 'F') hi = ch - 'A' + 10;
        else if (ch >= 'a' && ch <= 'f') hi = ch - 'a' + 10;
        if (cl >= '0' && cl <= '9') lo = cl - '0';
        else if (cl >= 'A' && cl <= 'F') lo = cl - 'A' + 10;
        else if (cl >= 'a' && cl <= 'f') lo = cl - 'a' + 10;
        b.push_back((hi << 4) | lo);
    }
    return b;
}

std::string b2h(const std::vector<uint8_t>& b) {
    std::ostringstream ss;
    ss << std::uppercase << std::hex << std::setfill('0');
    for (uint8_t x : b) ss << std::setw(2) << (int)x;
    return ss.str();
}

std::vector<uint32_t> exp(const std::vector<uint8_t>& key) {
    std::vector<uint32_t> w(44);
    for (int i = 0; i < 4; ++i) {
        w[i] = ((uint32_t)key[4 * i] << 24) | ((uint32_t)key[4 * i + 1] << 16) |
               ((uint32_t)key[4 * i + 2] << 8) | (uint32_t)key[4 * i + 3];
    }
    for (int i = 4; i < 44; ++i) {
        uint32_t t = w[i - 1];
        if (i % 4 == 0) {
            t = (t << 8) | (t >> 24);
            uint32_t b0 = S[(t >> 24) & 0xFF];
            uint32_t b1 = S[(t >> 16) & 0xFF];
            uint32_t b2 = S[(t >> 8) & 0xFF];
            uint32_t b3 = S[t & 0xFF];
            t = (b0 << 24) | (b1 << 16) | (b2 << 8) | b3;
            t ^= (uint32_t)RC[i / 4] << 24;
        }
        w[i] = w[i - 4] ^ t;
    }
    return w;
}

void sub(St& st) {
    for (int i = 0; i < 4; ++i)
        for (int j = 0; j < 4; ++j)
            st[i][j] = S[st[i][j]];
}

void isub(St& st) {
    for (int i = 0; i < 4; ++i)
        for (int j = 0; j < 4; ++j)
            st[i][j] = RS[st[i][j]];
}

void shift(St& st) {
    uint8_t t = st[1][0];
    st[1][0] = st[1][1]; st[1][1] = st[1][2]; st[1][2] = st[1][3]; st[1][3] = t;
    t = st[2][0]; st[2][0] = st[2][2]; st[2][2] = t;
    t = st[2][1]; st[2][1] = st[2][3]; st[2][3] = t;
    t = st[3][3];
    st[3][3] = st[3][2]; st[3][2] = st[3][1]; st[3][1] = st[3][0]; st[3][0] = t;
}

void ishift(St& st) {
    uint8_t t = st[1][3];
    st[1][3] = st[1][2]; st[1][2] = st[1][1]; st[1][1] = st[1][0]; st[1][0] = t;
    t = st[2][0]; st[2][0] = st[2][2]; st[2][2] = t;
    t = st[2][1]; st[2][1] = st[2][3]; st[2][3] = t;
    t = st[3][0];
    st[3][0] = st[3][1]; st[3][1] = st[3][2]; st[3][2] = st[3][3]; st[3][3] = t;
}

void mix(St& st) {
    auto xt = [](uint8_t a) -> uint8_t {
        return (a << 1) ^ ((a & 0x80) ? 0x1b : 0x00);
    };
    for (int c = 0; c < 4; ++c) {
        uint8_t s0 = st[0][c], s1 = st[1][c], s2 = st[2][c], s3 = st[3][c];
        st[0][c] = xt(s0) ^ (xt(s1) ^ s1) ^ s2 ^ s3;
        st[1][c] = s0 ^ xt(s1) ^ (xt(s2) ^ s2) ^ s3;
        st[2][c] = s0 ^ s1 ^ xt(s2) ^ (xt(s3) ^ s3);
        st[3][c] = (xt(s0) ^ s0) ^ s1 ^ s2 ^ xt(s3);
    }
}

uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t h = (a & 0x80);
        a <<= 1;
        if (h) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

void imix(St& st) {
    for (int c = 0; c < 4; ++c) {
        uint8_t s0 = st[0][c], s1 = st[1][c], s2 = st[2][c], s3 = st[3][c];
        st[0][c] = gmul(s0, 14) ^ gmul(s1, 11) ^ gmul(s2, 13) ^ gmul(s3, 9);
        st[1][c] = gmul(s0, 9)  ^ gmul(s1, 14) ^ gmul(s2, 11) ^ gmul(s3, 13);
        st[2][c] = gmul(s0, 13) ^ gmul(s1, 9)  ^ gmul(s2, 14) ^ gmul(s3, 11);
        st[3][c] = gmul(s0, 11) ^ gmul(s1, 13) ^ gmul(s2, 9)  ^ gmul(s3, 14);
    }
}

void add(St& st, const std::vector<uint32_t>& w, int r) {
    for (int c = 0; c < 4; ++c) {
        uint32_t val = w[r * 4 + c];
        st[0][c] ^= (val >> 24) & 0xFF;
        st[1][c] ^= (val >> 16) & 0xFF;
        st[2][c] ^= (val >> 8) & 0xFF;
        st[3][c] ^= val & 0xFF;
    }
}

std::vector<uint8_t> enc(const std::vector<uint8_t>& pt, const std::vector<uint8_t>& key) {
    auto w = exp(key);
    St st;
    for (int c = 0; c < 4; ++c)
        for (int r = 0; r < 4; ++r)
            st[r][c] = pt[c * 4 + r];
    add(st, w, 0);
    for (int r = 1; r <= 9; ++r) {
        sub(st);
        shift(st);
        mix(st);
        add(st, w, r);
    }
    sub(st);
    shift(st);
    add(st, w, 10);
    std::vector<uint8_t> ct(16);
    for (int c = 0; c < 4; ++c)
        for (int r = 0; r < 4; ++r)
            ct[c * 4 + r] = st[r][c];
    return ct;
}

std::vector<uint8_t> dec(const std::vector<uint8_t>& ct, const std::vector<uint8_t>& key) {
    auto w = exp(key);
    St st;
    for (int c = 0; c < 4; ++c)
        for (int r = 0; r < 4; ++r)
            st[r][c] = ct[c * 4 + r];
    add(st, w, 10);
    for (int r = 9; r >= 1; --r) {
        ishift(st);
        isub(st);
        add(st, w, r);
        imix(st);
    }
    ishift(st);
    isub(st);
    add(st, w, 0);
    std::vector<uint8_t> pt(16);
    for (int c = 0; c < 4; ++c)
        for (int r = 0; r < 4; ++r)
            pt[c * 4 + r] = st[r][c];
    return pt;
}

int main() {
    std::ifstream f("../problems/AES_TestVectors.csv");
    if (!f.is_open()) return 1;
    std::string line;
    std::getline(f, line);
    int passed = 0, total = 0;
    while (std::getline(f, line)) {
        if (line.empty()) continue;
        std::stringstream ss(line);
        std::string idx, cat, pt_h, k_h, ct_h;
        std::getline(ss, idx, ',');
        std::getline(ss, cat, ',');
        std::getline(ss, pt_h, ',');
        std::getline(ss, k_h, ',');
        std::getline(ss, ct_h, ',');
        
        auto pt = h2b(pt_h);
        auto k = h2b(k_h);
        auto computed = enc(pt, k);
        auto decrypted = dec(computed, k);
        
        bool ok = (b2h(computed) == ct_h && b2h(decrypted) == pt_h);
        if (ok) passed++;
        total++;
    }
    std::cout << "Results: " << passed << "/" << total << " passed\n";
    return 0;
}
